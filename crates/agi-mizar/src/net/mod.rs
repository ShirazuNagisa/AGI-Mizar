//! MizarNet: the direct path, from the desktop's side.
//!
//! Every other route this application offers goes somewhere first: the LAN
//! address is dialled across the operator's own network, and the relay carries
//! the bytes through a server. A punched connection is the one where the two
//! endpoints find each other and then speak directly, which is why it needs a
//! protocol of its own rather than another URL.
//!
//! ### What lives here, and what does not
//!
//! - [`identity`] is the endpoint key, *derived* from the tunnel secret the
//!   pairing already trusts. Holding the host secret holds the host's endpoint
//!   key; nothing new is stored and a reinstall does not change the id.
//! - [`wire`] is the packet format: a 15-byte header, five packet types, every
//!   integer big-endian.
//! - [`crypto`] is the handshake's output and the per-packet seal — X25519,
//!   HKDF for one key per direction, ChaCha20-Poly1305 with the packet number as
//!   the nonce.
//!
//! The socket, the punch, the reliability window and the signalling channel are
//! the next layer up and are not here yet: this module is the part that has a
//! written contract in `docs/p2p-wire-v1.md` and shared fixtures in
//! `protocol/fixtures/p2p/wire.json`, so it is the part that can be proved
//! against the phone's own implementation without a network at all.
//!
//! ### The one rule that shapes the tests
//!
//! Apple's CryptoKit signs Ed25519 with a randomized nonce, so the same key and
//! the same message produce different bytes on every run (measured 2026-10-25).
//! The fixture therefore pins *verification* and never equality: a decoded
//! hello is checked with `verify_signature`, and a decoded packet is re-encoded
//! to prove the codec, not to reproduce somebody else's signature.
//!
//! ### Why the protocol is not QUIC
//!
//! Despite the file name on the phone's side (`MizarNetQUICEngine`), nothing
//! here is QUIC: it is a small reliable datagram protocol with its own hello,
//! acknowledgement window and close frame. That is deliberate — a punch has to
//! survive a symmetric NAT, and the only thing that makes that work is *also*
//! sending over the same socket, every few hundred milliseconds, from the
//! moment the first packet is sent.

pub mod crypto;
pub mod identity;
pub mod session;
pub mod wire;

#[cfg(test)]
mod fixture_tests {
    //! The cross-language contract, read from the same file the phone emits.
    //!
    //! `protocol/fixtures/p2p/wire.json` is generated by `MizarNetFixtureEmitter`
    //! in MizarKit and copied here. Both sides decode it, so a change to either
    //! implementation that is not also a change to the fixture fails on the
    //! other side -- which is the only thing that keeps a hand-rolled wire
    //! format honest across two languages.

    use super::crypto;
    use super::identity::{verify_signature, Identity, Purpose, SIGNATURE_LENGTH};
    use super::wire::{Packet, PacketBody, PacketType};

    use serde_json::Value;

    fn fixture() -> Value {
        let text = include_str!("../../../../protocol/fixtures/p2p/wire.json");
        serde_json::from_str(text).expect("the fixture is JSON")
    }

    fn bytes(value: &Value, key: &str) -> Vec<u8> {
        let text = value
            .get(key)
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("{key} is a hex string"));
        hex(text)
    }

    fn hex(text: &str) -> Vec<u8> {
        assert!(text.len() % 2 == 0, "{text} is not hex");
        (0..text.len())
            .step_by(2)
            .map(|index| u8::from_str_radix(&text[index..index + 2], 16).expect("hex digits"))
            .collect()
    }

    fn text(value: &Value, key: &str) -> String {
        value
            .get(key)
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("{key} is a string"))
            .to_string()
    }

    /// A small integer, or a 64-bit id the fixture had to spell as a string.
    ///
    /// Swift's `JSONEncoder` writes a `UInt64` that does not fit `Int64` as a
    /// string, and a connection id covers the whole 64-bit space -- which is the
    /// same trap the TypeScript port hit with `number`. Both forms are read here
    /// so the fixture stays readable and the id stays exact.
    fn number(value: &Value, key: &str) -> u64 {
        match value.get(key) {
            Some(Value::Number(number)) => number
                .as_u64()
                .unwrap_or_else(|| panic!("{key} is not a u64")),
            Some(Value::String(text)) => text
                .parse()
                .unwrap_or_else(|_| panic!("{key} is not a u64 spelled as a string")),
            _ => panic!("{key} is missing"),
        }
    }

    #[test]
    fn an_identity_is_derived_from_the_secret_the_same_way_the_phone_derives_it() {
        let fixture = fixture();
        let identity = fixture.get("identity").expect("identity");
        let secret = bytes(identity, "secretHex");
        let derived = Identity::derive(&secret, Purpose::Host);

        // The endpoint id is what a ticket names, so this one string is the whole
        // identity contract: get it wrong and no phone will ever reach us.
        assert_eq!(derived.endpoint_id(), text(identity, "endpointId"));
        assert_eq!(derived.short_id(), text(identity, "shortId"));
        // 43 characters of base64url is a 32-byte key with no padding.
        assert_eq!(derived.endpoint_id().len(), 43);
        assert_eq!(derived.public_key().len(), 32);
    }

    #[test]
    fn a_signature_is_verified_and_never_compared() {
        let fixture = fixture();
        let identity = fixture.get("identity").expect("identity");
        let signature = bytes(identity, "signatureHex");
        let message = bytes(identity, "messageHex");
        assert_eq!(signature.len(), SIGNATURE_LENGTH);

        // Apple signs with a random nonce, so the fixture's bytes are a sample
        // to verify rather than a value to reproduce.
        assert!(verify_signature(
            &signature,
            &message,
            &text(identity, "endpointId")
        ));
        assert!(!verify_signature(
            &signature,
            b"a different message",
            &text(identity, "endpointId")
        ));
        // A key that is not 32 bytes is not this endpoint's key.
        assert!(!verify_signature(&signature, &message, "not a key"));
    }

    #[test]
    fn a_client_hello_decodes_and_re_encodes_to_the_same_bytes() {
        let fixture = fixture();
        let hello = fixture.get("clientHello").expect("clientHello");
        let packet = Packet::decode(&bytes(hello, "packetHex")).expect("a client hello decodes");

        assert_eq!(packet.packet_type(), PacketType::ClientHello);
        assert_eq!(packet.connection_id, number(hello, "connectionId"));

        let PacketBody::Hello {
            ref ephemeral,
            ref endpoint_id,
            ref signature,
        } = packet.body
        else {
            panic!("a client hello is a hello");
        };
        assert_eq!(ephemeral.to_vec(), bytes(hello, "ephemeralPublicKeyHex"));
        assert_eq!(endpoint_id, &text(hello, "endpointId"));
        assert_eq!(signature.to_vec(), bytes(hello, "signatureHex"));

        // The one thing the hello is for: the message it signs.
        let message = packet.handshake_message();
        assert_eq!(message, bytes(hello, "handshakeMessageHex"));
        assert!(verify_signature(signature, &message, endpoint_id));

        assert_eq!(packet.encode(), bytes(hello, "packetHex"));
    }

    #[test]
    fn a_data_packet_carries_its_number_its_acks_and_its_sealed_message() {
        let fixture = fixture();
        let data = fixture.get("data").expect("data");
        let packet = Packet::decode(&bytes(data, "packetHex")).expect("a data packet decodes");

        assert_eq!(packet.packet_type(), PacketType::Data);
        let PacketBody::Data {
            number: packet_number,
            ref acks,
            message_length,
            ref sealed,
        } = packet.body
        else {
            panic!("a data packet is data");
        };
        assert_eq!(packet_number as u64, number(data, "packetNumber"));
        assert_eq!(
            acks.iter().map(|ack| *ack as u64).collect::<Vec<_>>(),
            data.get("acks")
                .and_then(Value::as_array)
                .expect("acks")
                .iter()
                .filter_map(Value::as_u64)
                .collect::<Vec<_>>(),
        );
        assert_eq!(message_length as u64, number(data, "messageLength"));
        assert_eq!(sealed.to_vec(), bytes(data, "sealedHex"));

        // The authenticated data is the header, the number and the length: the
        // message length is inside the tag, so a fragment cannot be reframed.
        assert_eq!(
            packet.authenticated_data(),
            bytes(data, "authenticatedDataHex")
        );
        assert_eq!(packet.encode(), bytes(data, "packetHex"));
    }

    #[test]
    fn the_seal_opens_with_the_dialers_key_and_says_what_was_sent() {
        let fixture = fixture();
        let session = fixture.get("session").expect("session");
        let salt = crypto::session_salt(
            &text(session, "localEndpointId"),
            &text(session, "remoteEndpointId"),
        );
        assert_eq!(salt.to_vec(), bytes(session, "saltHex"));

        let shared: [u8; 32] = bytes(session, "sharedSecretHex").try_into().expect("32 bytes");
        let keys = crypto::session_keys(&shared, &salt);
        assert_eq!(
            keys.dialer_to_acceptor.to_vec(),
            bytes(session, "dialerToAcceptorKeyHex")
        );
        assert_eq!(
            keys.acceptor_to_dialer.to_vec(),
            bytes(session, "acceptorToDialerKeyHex")
        );

        let data = fixture.get("data").expect("data");
        let packet = Packet::decode(&bytes(data, "packetHex")).expect("a data packet decodes");
        let plaintext = crypto::open_packet(&packet, &keys.dialer_to_acceptor)
            .expect("the dialer's key opens the dialer's packet");
        assert_eq!(plaintext, bytes(data, "plaintextHex"));
        // The acceptor's key is a different key, and it must not open it.
        assert_eq!(
            crypto::open_packet(&packet, &keys.acceptor_to_dialer),
            Err(crypto::CryptoError::Open)
        );
    }

    #[test]
    fn the_two_sides_agree_on_a_shared_secret() {
        let fixture = fixture();
        let agreement = fixture.get("agreement").expect("agreement");
        let secret: [u8; 32] = bytes(agreement, "localSecretHex")
            .try_into()
            .expect("32 bytes");
        let remote: [u8; 32] = bytes(agreement, "remotePublicKeyHex")
            .try_into()
            .expect("32 bytes");
        let shared = crypto::agree(&secret, &remote);
        assert_eq!(shared.to_vec(), bytes(agreement, "sharedSecretHex"));
    }

    #[test]
    fn the_control_packets_are_every_kind_the_fixture_covers() {
        let fixture = fixture();
        let control = fixture.get("control").expect("control");

        let keepalive = Packet::decode(&bytes(control, "keepaliveHex")).expect("keepalive");
        assert_eq!(keepalive.packet_type(), PacketType::Keepalive);
        assert_eq!(keepalive.encode(), bytes(control, "keepaliveHex"));

        let ack = Packet::decode(&bytes(control, "ackHex")).expect("ack");
        let PacketBody::Ack { ref acks } = ack.body else {
            panic!("an ack is an ack");
        };
        assert_eq!(acks, &vec![3, 4, 5]);
        assert_eq!(ack.encode(), bytes(control, "ackHex"));

        let close = Packet::decode(&bytes(control, "closeHex")).expect("close");
        let PacketBody::Close { ref reason } = close.body else {
            panic!("a close is a close");
        };
        assert_eq!(reason, "bye");
        assert_eq!(close.encode(), bytes(control, "closeHex"));
    }

    #[test]
    fn a_packet_whose_length_field_disagrees_with_its_bytes_is_refused() {
        let fixture = fixture();
        let mut bytes = bytes(fixture.get("control").expect("control"), "keepaliveHex");
        bytes.push(0);
        // One datagram is one packet: a trailing byte is a different datagram.
        assert!(Packet::decode(&bytes).is_err());
    }
}
